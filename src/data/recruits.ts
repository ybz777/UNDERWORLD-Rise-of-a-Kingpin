// Generate procedural recruits to fill pool to 50+
const FIRST_NAMES = ['Aleksei', 'Konstantin', 'Damian', 'Rocco', 'Leopold', 'Mateo', 'Cassian', 'Jarek', 'Soren', 'Dante', 'Vanya', 'Radu', 'Zane', 'Lev', 'Goran', 'Anton', 'Piotr', 'Kaelen', 'Magnus', 'Oleg', 'Stjepan', 'Bojan', 'Dominic', 'Niko', 'Roman'];
const LAST_NAMES = ['Kozlov', 'Morozov', 'Varga', 'Petrov', 'Popov', 'Santoro', 'Castillo', 'Benoit', 'Lindholm', 'Novak', 'Ilic', 'Kovacs', 'Browning', 'Sterling', 'Garrick', 'Mercer', 'Drazen', 'Vane', 'Rostov', 'Solomon'];
const ROLES: MemberRole[] = ['Street Enforcer', 'Rifleman', 'Veteran', 'Bodyguard', 'Driver', 'Medic', 'Scout', 'Manager', 'Negotiator', 'Smuggler', 'Mechanic', 'Accountant', 'Fixer', 'Strategist', 'Intelligence Specialist', 'Business Manager'];
const PERSONALITIES: PersonalityTrait[] = ['Loyal', 'Greedy', 'Ambitious', 'Cowardly', 'Brave', 'Professional', 'Unstable', 'Charismatic', 'Aggressive', 'Cautious', 'Opportunistic'];

export function generateProceduralRecruit(prestige: number): RecruitTemplate {
  const fName = FIRST_NAMES[Math.floor(Math.random() * FIRST_NAMES.length)];
  const lName = LAST_NAMES[Math.floor(Math.random() * LAST_NAMES.length)];
  const role = ROLES[Math.floor(Math.random() * ROLES.length)];
  const personality = PERSONALITIES[Math.floor(Math.random() * PERSONALITIES.length)];
  const age = 22 + Math.floor(Math.random() * 32);

  const basePower = Math.min(95, Math.max(35, 45 + Math.floor(prestige * 0.4) + Math.floor(Math.random() * 25)));
  const combat = Math.min(98, Math.max(30, basePower + (role === 'Street Enforcer' || role === 'Veteran' || role === 'Rifleman' ? 15 : -10)));
  const accuracy = Math.min(98, Math.max(30, basePower + (role === 'Rifleman' || role === 'Scout' ? 12 : -5)));
  const stealth = Math.min(98, Math.max(25, basePower + (role === 'Scout' || role === 'Smuggler' ? 18 : -10)));
  const intelligence = Math.min(98, Math.max(35, basePower + (role === 'Strategist' || role === 'Accountant' || role === 'Fixer' ? 15 : -5)));
  const leadership = Math.min(98, Math.max(30, basePower + (role === 'Strategist' || role === 'Veteran' ? 10 : -8)));
  const charisma = Math.min(98, Math.max(25, basePower + (role === 'Negotiator' || role === 'Fixer' ? 20 : -10)));
  const nerves = Math.min(98, Math.max(30, basePower + (personality === 'Brave' || personality === 'Professional' ? 15 : -10)));

  const salary = Math.round((combat * 1.5 + intelligence * 1.2 + nerves * 1.2) * 1.1);
  const hiringCost = Math.round(salary * (8 + Math.random() * 6));

  return {
    name: `${fName} ${lName}`,
    age,
    role,
    personality,
    combat,
    accuracy,
    stealth,
    intelligence,
    leadership,
    charisma,
    nerves,
    loyalty: 50 + Math.floor(Math.random() * 40),
    morale: 65 + Math.floor(Math.random() * 30),
    discipline: 50 + Math.floor(Math.random() * 45),
    ambition: 40 + Math.floor(Math.random() * 55),
    greed: 30 + Math.floor(Math.random() * 60),
    specialization: `${role} Specialization`,
    salary,
    hiringCost,
    minPrestige: Math.max(0, Math.floor(prestige * 0.8)),
    bio: `Underworld operative operating in the regional underground circuit.`
  };
}

