export function generateActiveContracts(count: number = 6): Contract[] {
  const shuffled = [...CONTRACT_TEMPLATES].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count).map((tpl, idx) => ({
    ...tpl,
    id: `ct_${Date.now()}_${idx}_${Math.random().toString(36).substring(2, 6)}`,
    daysRemaining: tpl.timeLimitDays
  }));
}
